// --- versionString tests ---

func TestVersionString_Basic(t *testing.T) {
	got := versionString(BuildInfo{})
	if got == "" {
		t.Fatal("expected non-empty version string")
	}
	if !strings.HasPrefix(got, "pre-commit ") {
		t.Errorf("expected prefix 'pre-commit ', got %q", got)
	}
}

func TestVersionString_WithBuild(t *testing.T) {
	got := versionString(BuildInfo{
		Version: "1.2.3",
		Commit:  "abc123def456",
		Date:    "2025-01-01",
	})
	if !strings.Contains(got, "build 1.2.3") {
		t.Errorf("expected build version in output, got %q", got)
	}
	// Commit should be truncated to 8 chars.
	if !strings.Contains(got, "abc123de") {
		t.Errorf("expected truncated commit in output, got %q", got)
	}
	if !strings.Contains(got, "2025-01-01") {
		t.Errorf("expected date in output, got %q", got)
	}
}

func TestVersionString_DevVersion(t *testing.T) {
	got := versionString(BuildInfo{Version: "dev"})
	if strings.Contains(got, "build") {
		t.Errorf("did not expect build info for dev version, got %q", got)
	}
}

