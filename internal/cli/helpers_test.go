// --- isPreCommitHook tests ---

func TestIsPreCommitHook_Generated(t *testing.T) {
	content := "#!/bin/bash\n# File generated by pre-commit\nhook-impl --config=.pre-commit-config.yaml\n"
	if !isPreCommitHook(content) {
		t.Error("expected true for generated hook")
	}
}

func TestIsPreCommitHook_WithID(t *testing.T) {
	content := "#!/bin/bash\n# ID: pre-commit-pre-commit\npre-commit hook-impl\n"
	if !isPreCommitHook(content) {
		t.Error("expected true for hook with ID marker")
	}
}

func TestIsPreCommitHook_HookImpl(t *testing.T) {
	content := "#!/bin/bash\npre-commit hook-impl --hook-type=pre-commit\n"
	if !isPreCommitHook(content) {
		t.Error("expected true for hook-impl content")
	}
}

func TestIsPreCommitHook_NotPreCommit(t *testing.T) {
	content := "#!/bin/bash\necho 'hello world'\n"
	if isPreCommitHook(content) {
		t.Error("expected false for non-pre-commit hook")
	}
}

func TestIsPreCommitHook_Empty(t *testing.T) {
	if isPreCommitHook("") {
		t.Error("expected false for empty string")
	}
}

// --- sortedHookTypes tests ---

func TestSortedHookTypes(t *testing.T) {
	types := sortedHookTypes()
	if len(types) == 0 {
		t.Fatal("expected non-empty hook types list")
	}
	for i := 1; i < len(types); i++ {
		if types[i] < types[i-1] {
			t.Errorf("hook types not sorted: %q comes after %q", types[i], types[i-1])
		}
	}
	typeSet := make(map[string]bool)
	for _, ht := range types {
		typeSet[ht] = true
	}
	for _, expected := range []string{"pre-commit", "pre-push", "commit-msg", "post-checkout"} {
		if !typeSet[expected] {
			t.Errorf("expected hook type %q not found", expected)
		}
	}
}
