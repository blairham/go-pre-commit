// --- isPreCommitHook tests ---

// isPreCommitHook is upstream's hash rule: a script counts as ours by one of
// the hashes, whatever else it says.
func TestIsPreCommitHook(t *testing.T) {
	for _, tc := range []struct {
		name    string
		content string
		want    bool
	}{
		{"current hash", "#!/usr/bin/env bash\n# ID: 138fd403232d2ddd5efb44317e38bf03\n", true},
		{"prior hash", "#!/bin/sh\n# ID: e358c9dae00eac5d06b38dfdb1e33a8c\n", true},
		{"this port's script before the hash", "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n# ID: pre-commit-pre-push\n", true},
		{"mentions hook-impl only", "#!/bin/bash\npre-commit hook-impl --hook-type=pre-commit\n", false},
		{"generated-by line only", "#!/bin/bash\n# File generated by pre-commit\nexec pre-commit hook-impl\n", false},
		{"foreign", "#!/bin/bash\necho 'hello world'\n", false},
		{"empty", "", false},
	} {
		if got := isPreCommitHook(tc.content); got != tc.want {
			t.Errorf("%s: isPreCommitHook = %v, want %v", tc.name, got, tc.want)
		}
	}
}

// --- sortedHookTypes tests ---

func TestSortedHookTypes(t *testing.T) {
	types := sortedHookTypes()
	if len(types) == 0 {
		t.Fatal("expected non-empty hook types list")
	}
	for i := 1; i < len(types); i++ {
		if types[i] < types[i-1] {
			t.Errorf("hook types not sorted: %q comes after %q", types[i], types[i-1])
		}
	}
	typeSet := make(map[string]bool)
	for _, ht := range types {
		typeSet[ht] = true
	}
	for _, expected := range []string{"pre-commit", "pre-push", "commit-msg", "post-checkout"} {
		if !typeSet[expected] {
			t.Errorf("expected hook type %q not found", expected)
		}
	}
}
