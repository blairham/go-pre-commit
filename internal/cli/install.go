// hookTemplate is the shell script template installed into .git/hooks/
const hookTemplate = `#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: %s
set -eu -o pipefail

# start templated
ARGS=(hook-impl --config=%s --hook-type=%s)
# end templated

HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS+=(--hook-dir "$HERE" -- "$@")

if command -v pre-commit > /dev/null; then
    exec pre-commit "${ARGS[@]}"
else
    echo '` + "`" + `pre-commit` + "`" + ` not found. Did you forget to install it?' 1>&2
    exit 1
fi
`

// hookTypes maps short names to hook filenames.
var hookTypes = map[string]string{
	"pre-commit":         "pre-commit",
	"pre-merge-commit":   "pre-merge-commit",
	"pre-push":           "pre-push",
	"prepare-commit-msg": "prepare-commit-msg",
	"commit-msg":         "commit-msg",
	"post-checkout":      "post-checkout",
	"post-commit":        "post-commit",
	"post-merge":         "post-merge",
	"post-rewrite":       "post-rewrite",
	"pre-rebase":         "pre-rebase",
}

// InstallCommand implements the "install" command.
type InstallCommand struct {
	Meta *Meta
}

type installFlags struct {
	GlobalFlags
	HookTypes    []string `short:"t" long:"hook-type"            description:"The hook type(s) to install. May be specified multiple times."`
	AllowMissing bool     `          long:"allow-missing-config" description:"Allow the hook installation to succeed when no config is found."`
	Overwrite    bool     `short:"f" long:"overwrite"            description:"Overwrite existing hooks."`
	InstallHooks bool     `          long:"install-hooks"        description:"Install hook environments for all hooks in the config."`
}

func (c *InstallCommand) Run(args []string) int {
	var opts installFlags
	_, err := flags.ParseArgs(&opts, args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		return 1
	}

	// argparse rejects an unknown -t before main gets as far as the root.
	if !validHookTypes(opts.HookTypes) {
		return 1
	}

	if err = adjustArgsAndChdir(rootArgs{Config: &opts.Config}); err != nil {
		return fatalError(err)
	}

	// Upstream refuses outright: git would never run a hook written to
	// .git/hooks while core.hooksPath points elsewhere.
	if git.HasCoreHookPathsSet() {
		output.LogError("Cowardly refusing to install hooks with `core.hooksPath` set.\n" +
			"hint: `git config --unset-all core.hooksPath`")
		return 1
	}

	// Determine hook types to install.
	typesToInstall := installHookTypes(opts.Config, opts.HookTypes)

	// Validate hook types.
	if !validHookTypes(typesToInstall) {
		return 1
	}

	for _, hookType := range typesToInstall {
		hookFile, legacyFile, err := hookPaths(hookType)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error: %v\n", err)
			return 1
		}
		if err := os.MkdirAll(filepath.Dir(hookFile), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "Error: failed to create hooks directory: %v\n", err)
			return 1
		}

		// An existing hook that is not ours becomes the legacy hook, which
		// the installed script runs first ("migration mode").
		if _, err := os.Lstat(hookFile); err == nil && !isOurScript(hookFile) {
			if err := os.Rename(hookFile, legacyFile); err != nil {
				fmt.Fprintf(os.Stderr, "Error: failed to move existing hook %s: %v\n", hookFile, err)
				return 1
			}
		}

		if _, err := os.Stat(legacyFile); err == nil {
			if opts.Overwrite {
				if err := os.Remove(legacyFile); err != nil {
					fmt.Fprintf(os.Stderr, "Error: failed to remove %s: %v\n", legacyFile, err)
					return 1
				}
			} else {
				fmt.Printf("Running in migration mode with existing hooks at %s\nUse -f to use only pre-commit.\n", legacyFile)
			}
		}

		// Write the hook script.
		installID := "pre-commit-" + hookType
		content := fmt.Sprintf(hookTemplate, installID, opts.Config, hookType)

		if err := os.WriteFile(hookFile, []byte(content), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "Error: failed to write hook: %v\n", err)
			return 1
		}
		// WriteFile keeps an existing file's mode; make_executable does not.
		if err := os.Chmod(hookFile, 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "Error: %v\n", err)
			return 1
		}

		fmt.Printf("pre-commit installed at %s\n", hookFile)
	}

	// Install hook environments if requested.
	if opts.InstallHooks {
		if err := installAllHookEnvironments(opts.Config); err != nil {
			fmt.Fprintf(os.Stderr, "Error: %v\n", err)
			return 1
		}
	}

	return 0
}

func (c *InstallCommand) Help() string {
	return strings.TrimSpace(`
Usage: pre-commit install [options]

  Install the pre-commit script into .git/hooks/.
  By default installs a pre-commit hook. Use -t multiple times to install
  several hook types.

Options:

  -t, --hook-type=TYPE         The hook type(s) to install.
      --allow-missing-config   Allow installation when no config is found.
  -f, --overwrite              Overwrite existing hooks.
      --install-hooks          Install hook environments for all hooks.
  -c, --config=FILE            Path to alternate config file.
      --color=MODE             Whether to use color (auto, always, never).
`)
}

func (c *InstallCommand) Synopsis() string {
	return "Install the pre-commit script"
}

// UninstallCommand implements the "uninstall" command.
type UninstallCommand struct {
	Meta *Meta
}

type uninstallFlags struct {
	GlobalFlags
	HookTypes []string `short:"t" long:"hook-type" description:"Which hook type to uninstall. May be specified multiple times. (default: pre-commit)"`
}

func (c *UninstallCommand) Run(args []string) int {
	var opts uninstallFlags
	_, err := flags.ParseArgs(&opts, args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		return 1
	}

	if !validHookTypes(opts.HookTypes) {
		return 1
	}

	if err = adjustArgsAndChdir(rootArgs{Config: &opts.Config}); err != nil {
		return fatalError(err)
	}

	exit := 0
	for _, ht := range installHookTypes(opts.Config, opts.HookTypes) {
		hookFile, legacyFile, err := hookPaths(ht)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error: %v\n", err)
			return 1
		}

		// A hook that is missing or not ours is left alone, silently.
		if !isOurScript(hookFile) {
			continue
		}

		if err := os.Remove(hookFile); err != nil {
			fmt.Fprintf(os.Stderr, "Error: failed to remove hook: %v\n", err)
			exit = 1
			continue
		}
		fmt.Printf("%s uninstalled\n", ht)

		if _, err := os.Stat(legacyFile); err == nil {
			if err := os.Rename(legacyFile, hookFile); err != nil {
				fmt.Fprintf(os.Stderr, "Error: failed to restore %s: %v\n", legacyFile, err)
				exit = 1
				continue
			}
			fmt.Printf("Restored previous hooks to %s\n", hookFile)
		}
	}
	return exit
}

func (c *UninstallCommand) Help() string {
	return strings.TrimSpace(`
Usage: pre-commit uninstall [options]

  Remove the pre-commit hook from .git/hooks/.

Options:

  -t, --hook-type=TYPE   The hook type to uninstall. May be repeated. (default: pre-commit)
  -c, --config=FILE      Path to alternate config file.
      --color=MODE       Whether to use color (auto, always, never).
`)
}

func (c *UninstallCommand) Synopsis() string {
	return "Uninstall the pre-commit script"
}

