// hookTemplate is upstream's resources/hook-tmpl, which install fills in
// between the templated markers. The one intended difference is how it runs
// pre-commit: upstream pins the Python that installed it (INSTALL_PYTHON) and
// falls back to `pre-commit` on PATH; this port has no interpreter to pin, so
// it runs `pre-commit` from PATH, and its not-found hint does not mention a
// virtualenv. The ID line carries upstream's CURRENT_HASH, which is how each
// tool recognizes the other's script as its own (is_our_script).
const hookTemplate = `#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03

# start templated
ARGS=(hook-impl)
# end templated

HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS+=(--hook-dir "$HERE" -- "$@")

if command -v pre-commit > /dev/null; then
    exec pre-commit "${ARGS[@]}"
else
    echo '` + "`" + `pre-commit` + "`" + ` not found.  Did you forget to install it?' 1>&2
    exit 1
fi
`

// The hashes upstream identifies its hook scripts by: CURRENT_HASH is in the
// script it writes today, PRIOR_HASHES in those older releases wrote.
const currentHash = "138fd403232d2ddd5efb44317e38bf03"

var priorHashes = []string{
	"4d9958c90bc262f47553e2c073f14cfe",
	"d8ee923c46731b42cd95cc869add4062",
	"49fd668cb42069aa1b6048464be5d395",
	"79f09a650522a87b0da915d0d983b2de",
	"e358c9dae00eac5d06b38dfdb1e33a8c",
}

const (
	templateStart = "# start templated\n"
	templateEnd   = "# end templated\n"
)

// hookScript is the body of upstream's _install_hook_script: the template
// with its templated section replaced by the hook-impl arguments, quoted as
// shlex.join quotes them.
func hookScript(configFile, hookType string, skipOnMissingConfig bool) string {
	args := []string{"hook-impl", "--config=" + configFile, "--hook-type=" + hookType}
	if skipOnMissingConfig {
		args = append(args, "--skip-on-missing-config")
	}
	quoted := make([]string, len(args))
	for i, a := range args {
		quoted[i] = config.ShlexQuote(a)
	}

	before, rest, _ := strings.Cut(hookTemplate, templateStart)
	_, after, _ := strings.Cut(rest, templateEnd)

	var b strings.Builder
	// Upstream writes /bin/sh first on Windows, where bash may not be on
	// PATH; git for Windows' sh is bash in POSIX mode and runs the rest.
	if runtime.GOOS == "windows" {
		b.WriteString("#!/bin/sh\n")
	}
	b.WriteString(before + templateStart)
	b.WriteString("ARGS=(" + strings.Join(quoted, " ") + ")\n")
	b.WriteString(templateEnd + after)
	return b.String()
}

